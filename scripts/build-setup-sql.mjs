#!/usr/bin/env node
/**
 * Concatenate the migrations into supabase/setup.sql.
 *
 * setup.sql is what someone pastes into the Supabase SQL Editor to build a new
 * project in one go. Keeping it generated rather than hand-assembled is the
 * only way it stays truthful: a migration added and not copied across produces
 * a setup file that builds a database the application no longer expects.
 */
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const migrationsDir = join(root, "supabase", "migrations");
const target = join(root, "supabase", "setup.sql");

const files = readdirSync(migrationsDir)
  .filter((name) => name.endsWith(".sql"))
  .sort();

if (files.length === 0) {
  console.error("No migrations found.");
  process.exit(1);
}

const header = `-- =============================================================================
-- Mall Consultants Install Dispatch -- COMPLETE DATABASE SETUP
-- =============================================================================
-- Paste this whole file into the Supabase SQL Editor and press Run. It builds
-- every table, security rule and pricing calculation the app needs, including
-- the service price list.
--
-- Safe to run once on a brand-new project. Running it twice will error on the
-- second run, which is harmless -- it just means it is already set up.
--
-- Generated from supabase/migrations/ by scripts/build-setup-sql.mjs.
-- Do not edit this file directly; edit the migrations and regenerate.
-- =============================================================================

`;

const body = files
  .map((name) => {
    const banner = [
      "",
      "-- ###########################################################################",
      `-- ##  ${name}`,
      "-- ###########################################################################",
      "",
    ].join("\n");
    return banner + readFileSync(join(migrationsDir, name), "utf8");
  })
  .join("\n");

writeFileSync(target, `${header}${body}\n`);

console.log(`setup.sql rebuilt from ${files.length} migrations`);
