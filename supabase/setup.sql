  started_at            timestamptz,
  completed_at          timestamptz,
  completion_notes      text,

  -- Review ---------------------------------------------------------------
  approved_at           timestamptz,
  approved_by           uuid references public.profiles (id) on delete set null,
  rework_requested_at   timestamptz,
  rework_notes          text,
