  jp.contractor_percentage_bps,
  jp.contractor_labor_pay_cents,
  jp.mall_share_cents,
  j.contractor_miles,
  j.excluded_miles,
  j.payable_miles,
  j.mileage_rate,
  j.mileage_payment_cents,
  j.materials_cents,
