  paid_at               timestamptz,
  payment_reference     text,
  payment_method        text,
  paid_by               uuid references public.profiles (id) on delete set null,

  -- Exceptional states ---------------------------------------------------
  hold_reason           text,
  cancel_reason         text,
  unfilled_at           timestamptz,

