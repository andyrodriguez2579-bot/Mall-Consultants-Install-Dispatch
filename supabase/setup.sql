-- ---------------------------------------------------------------------------
-- Expiry sweep. Closes dispatch rounds whose window has elapsed and marks the
-- job 'unfilled' so an admin can re-offer it. Safe to call repeatedly.
-- ---------------------------------------------------------------------------
